import { useEffect, useState } from "react";
import { fetchBranding } from "../api";
import { AdminPickCard } from "./AdminPickCard";
import { PickBookingCodes } from "./PickBookingCodes";
import { useAuth } from "../lib/AuthContext";
import type { AdminPick } from "../types";

const TIER_ORDER = ["low", "medium", "high"] as const;

function tierOf(pick: AdminPick): (typeof TIER_ORDER)[number] | null {
  for (const tier of TIER_ORDER) {
    if (pick.source === `system_weekly_${tier}`) return tier;
  }
  return null;
}

/** The three system-generated weekly accumulators (Low / Medium / High risk,
 * 10-15 legs each, pooled across the biggest leagues) app.risk_picks
 * publishes -- see AdminPick.source. Like the daily ones (DailyPicksSection)
 * a tier is set by how likely each *leg* is (Low 85%+, Medium 70-85%, High
 * 55-70%), built from the week's matches rather than just the next day or
 * two. They used to be defined by combined bookmaker odds, which needed a
 * captured price on every leg and published nothing the week none existed.
 * Renders nothing until a tier has been generated, same "no empty-state"
 * reasoning AdminPicksSection already applies.
 *
 * Each card also carries a live booking panel (PickBookingCodes), same as
 * RandomPicksSection's -- these three accumulators are regenerated by cron
 * with no human in the loop, same as the random draws, so the admin-pasted
 * booking_code + WhatsApp fallback AdminPicksSection relies on for a
 * human-curated pick isn't a given here either.
 *
 * ``allPicks`` is the full GET /api/predictions/admin-picks response,
 * fetched once by the caller (AIPicks) and shared across this section,
 * AdminPicksSection and RandomPicksSection -- see AIPicks's own docstring
 * for why this section no longer fetches it itself. */
export function WeeklyPicksSection({ picks: allPicks }: { picks: AdminPick[] | null }) {
  const { user, accessStatus } = useAuth();
  const viewerHasPremium = user?.role === "superadmin" || !!accessStatus?.has_access;
  const [whatsapp, setWhatsapp] = useState<string | null>(null);

  const picks = allPicks
    ? allPicks
        .filter((pick) => tierOf(pick) !== null)
        .sort((a, b) => TIER_ORDER.indexOf(tierOf(a)!) - TIER_ORDER.indexOf(tierOf(b)!))
    : null;

  const needsWhatsapp = picks?.some((p) => p.has_booking_code && !p.booking_code) ?? false;
  useEffect(() => {
    if (!needsWhatsapp || whatsapp) return;
    fetchBranding()
      .then((b) => setWhatsapp(b.contact_whatsapp || null))
      .catch(() => {});
  }, [needsWhatsapp, whatsapp]);

  if (!picks || picks.length === 0) return null;

  return (
    <div className="section-reveal">
      <div className="section-header">
        <h2>This Week's Picks</h2>
        <span className="meta">
          Three slips of 10 to 15 games from the week's matches, grouped by how likely each game is: 85% or more, 70
          to 85%, and 55 to 70%. Every game must win, so each slip's own chance is shown on it.
        </span>
      </div>
      <div className="picks-grid">
        {picks.map((pick) => (
          <div key={pick.id}>
            <AdminPickCard pick={pick} whatsapp={whatsapp} />
            <PickBookingCodes pick={pick} viewerHasPremium={viewerHasPremium} />
          </div>
        ))}
      </div>
    </div>
  );
}
