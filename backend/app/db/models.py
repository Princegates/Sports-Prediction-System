class Base(DeclarativeBase):
    pass


class User(Base):
    """A registered account. Logging in only requires ``status`` to not be
    ``suspended`` -- whether the account can use the prediction features is a
    separate question, answered by whether it holds a live ``AccessGrant``
    (below), not by anything on this row. That split is what lets an account
    whose access has lapsed still sign in and redeem a new code, instead of
    being locked out of the API entirely.
    """

    __tablename__ = "users"

    id: Mapped[int] = mapped_column(primary_key=True)
    email: Mapped[str] = mapped_column(String(255), unique=True, index=True)
    name: Mapped[str] = mapped_column(String(120))
    password_hash: Mapped[str] = mapped_column(String(255))

    # "user" or "superadmin"
    role: Mapped[str] = mapped_column(String(16), default="user")
    # "active" / "suspended"
    status: Mapped[str] = mapped_column(String(16), default="active")

    # Personal display preferences, carried with the account (not just the
    # browser) so they follow the user across devices.
    theme: Mapped[str | None] = mapped_column(String(16), nullable=True)
    accent_profile: Mapped[str | None] = mapped_column(String(32), nullable=True)

    created_at: Mapped[dt.datetime] = mapped_column(DateTime, default=dt.datetime.utcnow)


