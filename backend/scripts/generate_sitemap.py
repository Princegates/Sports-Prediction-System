#!/usr/bin/env python3
"""Regenerates frontend/public/sitemap.xml: the static marketing pages plus
one <url> per fixture currently live on GET /api/public/fixtures/{id} --
the public, no-login prediction-preview pages (frontend/src/pages/
FixturePreview.tsx) that exist specifically so a search engine has real,
indexable content for "<team> vs <team> prediction" searches.

Run after the daily/weekly fixture refresh (see
.github/workflows/refresh-predictions.yml), which also commits the result
back to the repo if it changed -- Cloudflare Pages redeploys on that push,
same as any other content change.

Deliberately NOT limited to "the next few" fixtures the way the public API's
own default is: a sitemap is for search engines, which have no 20-item
pagination to work around, so this lists every fixture inside the same
public-safe window the single-fixture endpoint itself will actually answer
for (MAX_PUBLIC_FIXTURE_DAYS_AHEAD) -- listing more than that would just
point crawlers at URLs that 404.

    python scripts/generate_sitemap.py
    python scripts/generate_sitemap.py --dry-run
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
import sys
import unicodedata
from pathlib import Path
from xml.sax.saxutils import escape

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from sqlalchemy import select

from app.api.routes_public import MAX_PUBLIC_FIXTURE_DAYS_AHEAD
from app.db.migrate import init_db
from app.db.models import Match
from app.db.session import SessionLocal, engine

SITE_URL = "https://soccaintel.com"
SITEMAP_PATH = Path(__file__).resolve().parents[2] / "frontend" / "public" / "sitemap.xml"

# Mirrors frontend/src/lib/slug.ts's fixtureSlug/slugifyWord -- doesn't have
# to match byte-for-byte (the frontend only ever parses the leading id back
# out, see that file's own docstring), but a consistent URL is a better
# experience than two different slugs for the same match depending on which
# side built the link.
_NON_ALNUM = re.compile(r"[^a-z0-9]+")


def _slugify_word(s: str) -> str:
    normalized = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode("ascii")
    return _NON_ALNUM.sub("-", normalized.lower()).strip("-")


def fixture_slug(match: Match) -> str:
    teams = f"{_slugify_word(match.home_team.name)}-vs-{_slugify_word(match.away_team.name)}"
    return f"{match.id}-{teams}" if teams.strip("-") else str(match.id)


STATIC_URLS = [
    ("/", "daily", "1.0"),
    ("/how-it-works", "monthly", "0.8"),
    ("/fixtures", "daily", "0.9"),
    ("/responsible", "yearly", "0.5"),
    ("/register", "yearly", "0.4"),
    ("/login", "yearly", "0.3"),
]


def render_sitemap(fixture_slugs: list[str]) -> str:
    lines = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        "<!--",
        "  Regenerated by backend/scripts/generate_sitemap.py -- do not hand-edit the",
        "  <url> list below; change STATIC_URLS in that script instead. See its own",
        "  docstring for why the fixture URLs come and go on their own.",
        "",
        "  lastmod is left out rather than guessed: this file isn't generated from",
        "  real per-page modification dates, and a fabricated one is worse than none.",
        "-->",
        '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
    ]
    for path, changefreq, priority in STATIC_URLS:
        lines += [
            "  <url>",
            f"    <loc>{escape(SITE_URL + path)}</loc>",
            f"    <changefreq>{changefreq}</changefreq>",
            f"    <priority>{priority}</priority>",
            "  </url>",
        ]
    for slug in fixture_slugs:
        lines += [
            "  <url>",
            f"    <loc>{escape(f'{SITE_URL}/predict/{slug}')}</loc>",
            "    <changefreq>hourly</changefreq>",
            "    <priority>0.7</priority>",
            "  </url>",
        ]
    lines.append("</urlset>")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dry-run", action="store_true", help="Print what would be written without writing it.")
    args = parser.parse_args()

    sys.stdout.reconfigure(line_buffering=True)

    init_db(engine)
    db = SessionLocal()
    try:
        now = dt.datetime.utcnow()
        matches = db.execute(
            select(Match)
            .where(Match.date >= now, Match.date < now + dt.timedelta(days=MAX_PUBLIC_FIXTURE_DAYS_AHEAD))
            .order_by(Match.date.asc())
        ).scalars().all()
        slugs = [fixture_slug(m) for m in matches]
        print(f"{len(slugs)} upcoming fixture(s) within {MAX_PUBLIC_FIXTURE_DAYS_AHEAD} days.")
    finally:
        db.close()

    content = render_sitemap(slugs)

    if args.dry_run:
        print(content)
        return

    SITEMAP_PATH.write_text(content)
    print(f"Wrote {SITEMAP_PATH}")


if __name__ == "__main__":
    main()
